-- 엔티티 매핑(Hibernate 6 / PostgreSQL) 기준 초기 스키마

create table users (
    id                  bigint generated by default as identity primary key,
    email               varchar(255) not null,
    password            varchar(255),
    role                varchar(255) not null check (role in ('USER', 'ADMIN')),
    provider            varchar(255) not null check (provider in ('LOCAL', 'GOOGLE', 'KAKAO', 'NAVER')),
    provider_id         varchar(255),
    nickname            varchar(255),
    nickname_normalized varchar(255),
    constraint uk_users_email unique (email),
    constraint uk_users_nickname_normalized unique (nickname_normalized),
    constraint uk_users_provider_provider_id unique (provider, provider_id)
);

create table refresh_tokens (
    id           bigint generated by default as identity primary key,
    user_id      bigint       not null,
    token_hash   varchar(64)  not null,
    token_family varchar(36)  not null,
    expires_at   timestamp(6) not null,
    revoked      boolean      not null,
    issued_at    timestamp(6),
    constraint uk_refresh_tokens_token_hash unique (token_hash)
);

create table user_profiles (
    id               bigint generated by default as identity primary key,
    user_id          bigint not null,
    gender           varchar(255) check (gender in ('MAN', 'WOMAN')),
    age              integer,
    height_cm        float(53),
    weight_kg        float(53),
    experience_level varchar(255) check (experience_level in ('BEGINNER', 'INTERMEDIATE', 'ADVANCED')),
    goal             varchar(255),
    created_at       timestamp(6),
    updated_at       timestamp(6),
    constraint uk_user_profiles_user_id unique (user_id),
    constraint fk_user_profiles_user foreign key (user_id) references users (id)
);

create table user_profile_primary_exercises (
    user_profile_id bigint       not null,
    exercise_type   varchar(255) not null check (exercise_type in ('RUNNING', 'BOXING')),
    primary key (user_profile_id, exercise_type),
    constraint fk_user_profile_primary_exercises_profile foreign key (user_profile_id) references user_profiles (id)
);

create table workout (
    id                bigint generated by default as identity primary key,
    dtype             varchar(31) not null,
    user_id           bigint      not null,
    type              varchar(255) check (type in ('RUNNING', 'BOXING')),
    duration_minutes  integer,
    memo              varchar(255),
    workout_date_time timestamp(6),
    created_at        timestamp(6),
    updated_at        timestamp(6),
    -- RunningWorkout
    distance_km       float(53),
    place             varchar(255),
    calories_burned   integer,
    -- BoxingWorkout
    rounds            integer,
    sparring_partner  varchar(255),
    technique_type    varchar(255) check (technique_type in ('SHADOW', 'MITT', 'SPARRING')),
    constraint fk_workout_user foreign key (user_id) references users (id)
);

create table workout_detail (
    id               bigint generated by default as identity primary key,
    workout_id       bigint,
    sequence         integer,
    label            varchar(255),
    duration_seconds integer,
    note             varchar(255),
    constraint fk_workout_detail_workout foreign key (workout_id) references workout (id)
);

-- MySQL(InnoDB)은 FK 컬럼에 인덱스를 자동 생성하지만 PostgreSQL은 만들지 않으므로 기존과 동일하게 맞춘다
create index idx_workout_user_id on workout (user_id);
create index idx_workout_detail_workout_id on workout_detail (workout_id);
