-- 운동 종료 후 몸상태 기록 --
create table workout_condition (
    id             bigint generated by default as identity primary key,
    workout_id     bigint  not null,
    rpe            integer not null check (rpe between 1 and 10),
    body_condition integer not null check (body_condition between 1 and 10),
    memo           varchar(255),
    created_at     timestamp(6),
    updated_at     timestamp(6),

    -- 운동 하나에 컨디션은 한개 --
    constraint uk_workout_condition_workout_id unique (workout_id),

    -- workout_id에는 workout 테이블에 존재하는 번호만 넣을 수 있고,  운동 삭제 시 컨디션도 같이 삭제--
    constraint fk_workout_condition_workout foreign key (workout_id) references workout (id) on delete cascade
);

-- 통증 부위별 강도 (행이 없으면 통증 없음, 통증 기준 1~5) --
create table workout_condition_pain (
    workout_condition_id bigint       not null,
    body_part            varchar(255) not null check (body_part in (
        'NECK', 'SHOULDER', 'ELBOW', 'WRIST_HAND', 'LOWER_BACK', 'HIP',
        'THIGH', 'KNEE', 'CALF_SHIN', 'ANKLE', 'FOOT', 'OTHER'
    )),
    intensity            integer      not null check (intensity between 1 and 5),

    -- 한 컨디션에 같은 부위는 한번만 입력 --
    primary key (workout_condition_id, body_part),

    constraint fk_workout_condition_pain_condition foreign key (workout_condition_id) references workout_condition (id) on delete cascade
);
