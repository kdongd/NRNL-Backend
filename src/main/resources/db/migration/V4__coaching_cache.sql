-- AI 코칭 결과 캐시 --
-- 회원당 1행. 마지막 컨디션 id가 저장 당시와 같으면 LLM을 다시 부르지 않고 저장된 코칭을 돌려줍니다.
create table coaching_cache (
    id                bigint generated by default as identity primary key,
    user_id           bigint not null,
    last_condition_id bigint not null,
    -- LLM이 생성한 코칭(summary, explanation, recommendations, caution)을 JSON 문자열로 저장 --
    advice            text   not null,
    created_at        timestamp(6),
    updated_at        timestamp(6),

    constraint uk_coaching_cache_user_id unique (user_id),
    constraint fk_coaching_cache_user foreign key (user_id) references users (id)
);
