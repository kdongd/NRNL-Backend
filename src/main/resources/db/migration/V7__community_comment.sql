
-- NRNL 커뮤니티 댓글 테이블 생성
-- 회원 1명은 여러 댓글을 작성할 수 있고 게시글 1개에는 여러 댓글이 달릴 수 있음

CREATE TABLE community_comment (

    -- 댓글 고유번호 (PK)
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 댓글이 작성된 게시글 (FK)
    post_id BIGINT NOT NULL,

    -- 댓글 작성자 (FK)
    user_id BIGINT NOT NULL,

    -- 댓글 내용 (최대 200자)
    content VARCHAR(200) NOT NULL,

    -- 댓글 최초 작성 시간
    created_at TIMESTAMP(6) NOT NULL,

    -- 댓글 마지막 수정 시간
    updated_at TIMESTAMP(6) NOT NULL,

    -- 게시글 외래 키
    -- 게시글 삭제 시 해당 댓글도 함께 삭제
    CONSTRAINT fk_community_comment_post
        FOREIGN KEY (post_id)
        REFERENCES community_post(id)
        ON DELETE CASCADE,

    -- 회원 외래 키
    CONSTRAINT fk_community_comment_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),

    -- 공백 댓글 저장 방지
    CONSTRAINT chk_community_comment_content_not_blank
        CHECK (LENGTH(TRIM(content)) > 0)
);

-- 게시글별 댓글을 작성순으로 조회하기 위한 인덱스
CREATE INDEX idx_community_comment_post_created
    ON community_comment(post_id, created_at ASC, id ASC);

-- 회원별 댓글 조회 및 회원 삭제 처리 시 활용
CREATE INDEX idx_community_comment_user_id
    ON community_comment(user_id);
