
-- NRNL 커뮤니티 게시글 및 댓글 좋아요 테이블 생성
-- 회원 1명은 여러 게시글과 댓글에 좋아요를 누를 수 있음
-- 동일 회원의 동일 대상 중복 좋아요 방지

-- 게시글 좋아요
CREATE TABLE community_post_like (

    -- 좋아요 고유번호 (PK)
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 좋아요 대상 게시글 (FK)
    post_id BIGINT NOT NULL,

    -- 좋아요를 누른 회원 (FK)
    user_id BIGINT NOT NULL,

    -- 게시글 삭제 시 좋아요 함께 삭제
    CONSTRAINT fk_community_post_like_post
        FOREIGN KEY (post_id)
        REFERENCES community_post(id)
        ON DELETE CASCADE,

    -- 회원 참조
    CONSTRAINT fk_community_post_like_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),

    -- 동일 회원의 동일 게시글 중복 좋아요 방지
    CONSTRAINT uk_community_post_like_post_user
        UNIQUE (post_id, user_id)
);

-- 회원별 좋아요 조회 및 FK 관련 작업
CREATE INDEX idx_community_post_like_user_id
    ON community_post_like(user_id);


-- 댓글 좋아요
CREATE TABLE community_comment_like (

    -- 좋아요 고유번호 (PK)
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 좋아요 대상 댓글 (FK)
    comment_id BIGINT NOT NULL,

    -- 좋아요를 누른 회원 (FK)
    user_id BIGINT NOT NULL,

    -- 댓글 삭제 시 좋아요 함께 삭제
    CONSTRAINT fk_community_comment_like_comment
        FOREIGN KEY (comment_id)
        REFERENCES community_comment(id)
        ON DELETE CASCADE,

    -- 회원 참조
    CONSTRAINT fk_community_comment_like_user
        FOREIGN KEY (user_id)
        REFERENCES users(id),

    -- 동일 회원의 동일 댓글 중복 좋아요 방지
    CONSTRAINT uk_community_comment_like_comment_user
        UNIQUE (comment_id, user_id)
);

-- 회원별 좋아요 조회 및 FK 관련 작업
CREATE INDEX idx_community_comment_like_user_id
    ON community_comment_like(user_id);
