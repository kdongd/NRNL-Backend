CREATE TABLE crew (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leader_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(20) NOT NULL,
    description VARCHAR(500) NOT NULL,
    capacity INTEGER NOT NULL,
    status VARCHAR(10) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_crew_leader UNIQUE (leader_id),
    CONSTRAINT ck_crew_name CHECK (name COLLATE "C" ~ '^[가-힣A-Za-z0-9]{2,20}$'),
    CONSTRAINT ck_crew_description CHECK (char_length(description) BETWEEN 10 AND 500 AND description !~ '^[[:space:]]*$'),
    CONSTRAINT ck_crew_capacity CHECK (capacity IN (10, 30, 50, 70, 100)),
    CONSTRAINT ck_crew_status CHECK (status IN ('OPEN', 'CLOSED'))
);

CREATE UNIQUE INDEX uk_crew_name ON crew (lower(name COLLATE "C"));
CREATE INDEX idx_crew_latest ON crew (created_at DESC, id DESC);

CREATE TABLE crew_sport (
    crew_id BIGINT NOT NULL REFERENCES crew(id) ON DELETE CASCADE,
    sport VARCHAR(10) NOT NULL,
    PRIMARY KEY (crew_id, sport),
    CONSTRAINT ck_crew_sport CHECK (sport IN ('RUNNING', 'BOXING'))
);

CREATE TABLE crew_member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id BIGINT NOT NULL REFERENCES crew(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    CONSTRAINT uk_crew_member UNIQUE (crew_id, user_id)
);

CREATE INDEX idx_crew_member_user ON crew_member (user_id);

-- 크루와 크루장 멤버십을 같은 트랜잭션에서 생성한다.
ALTER TABLE crew ADD CONSTRAINT fk_crew_leader_membership
    FOREIGN KEY (id, leader_id) REFERENCES crew_member (crew_id, user_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE crew_application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id BIGINT NOT NULL REFERENCES crew(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    status VARCHAR(10) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_crew_application_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_crew_application_resolution CHECK ((status = 'PENDING') = (resolved_at IS NULL))
);

CREATE UNIQUE INDEX uk_crew_application_pending ON crew_application (crew_id, user_id)
    WHERE status = 'PENDING';
CREATE INDEX idx_crew_application_latest ON crew_application (crew_id, created_at DESC, id DESC);
CREATE INDEX idx_crew_application_user ON crew_application (user_id);
